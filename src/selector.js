import { createServer } from 'node:http';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { exec } from 'node:child_process';
import { downloadM3u, parseM3u, buildM3u, inferCategory } from './m3u.js';

const PORT = 3737;
const ALLOWLIST_PATH = 'config/channels-allowlist.json';
const SELECTED_PATH  = 'config/channels-selected.json';
const PLAYLIST_PATH  = 'output/playlist.m3u';

// ─── Main ────────────────────────────────────────────────────────────────────

async function main() {
  const m3uUrl = process.env.PROVIDER_M3U_URL;
  if (!m3uUrl) {
    console.error('ERROR: PROVIDER_M3U_URL env var not set');
    console.error('Usage: PROVIDER_M3U_URL="http://host/get.php?username=X&password=Y&type=m3u_plus" node src/selector.js');
    process.exit(1);
  }

  console.log('[selector] Fetching M3U playlist...');
  const m3uText = await downloadM3u(m3uUrl);
  const channels = parseM3u(m3uText);
  console.log(`[selector] Parsed ${channels.length} channels in ${[...new Set(channels.map(c => c.groupTitle))].length} groups`);

  const prevSelected = existsSync(SELECTED_PATH)
    ? JSON.parse(readFileSync(SELECTED_PATH, 'utf8'))
    : { selected: [], favorites: [] };

  const html = buildHtml(channels, prevSelected);

  const server = createServer((req, res) => {
    if (req.method === 'GET' && req.url === '/') {
      res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
      res.end(html);
      return;
    }
    if (req.method === 'POST' && req.url === '/save') {
      let body = '';
      req.on('data', c => body += c);
      req.on('end', () => {
        try {
          const { selected, favorites } = JSON.parse(body);
          saveSelection(channels, selected, favorites);
          res.writeHead(200, { 'Content-Type': 'application/json' });
          res.end(JSON.stringify({ ok: true, count: selected.length, favCount: favorites.length }));
        } catch (err) {
          res.writeHead(400);
          res.end(JSON.stringify({ error: err.message }));
        }
      });
      return;
    }
    res.writeHead(404);
    res.end();
  });

  server.listen(PORT, '127.0.0.1', () => {
    const url = `http://localhost:${PORT}`;
    console.log(`\n[selector] ✓ Ready at ${url}\n`);
    const open = process.platform === 'win32' ? `start ${url}` : process.platform === 'darwin' ? `open ${url}` : `xdg-open ${url}`;
    exec(open);
  });
}

// ─── Save Selection ──────────────────────────────────────────────────────────

function saveSelection(allChannels, selectedIds, favoriteIds) {
  const selectedSet = new Set(selectedIds);
  const favSet      = new Set(favoriteIds);

  writeFileSync(SELECTED_PATH, JSON.stringify({ selected: selectedIds, favorites: favoriteIds }, null, 2));
  console.log(`[selector] Saved: ${selectedIds.length} channels, ${favoriteIds.length} favorites`);

  // Update EPG allowlist
  const allowlist = {
    _comment: `Generated by selector on ${new Date().toISOString().slice(0, 10)}`,
    channels: allChannels
      .filter(ch => selectedSet.has(ch.tvgId) && ch.tvgId)
      .map(ch => ({ 'tvg-id': ch.tvgId, category: inferCategory(ch.groupTitle) })),
  };
  writeFileSync(ALLOWLIST_PATH, JSON.stringify(allowlist, null, 2));
  console.log(`[selector] Updated ${ALLOWLIST_PATH} (${allowlist.channels.length} entries with tvg-id)`);

  // Build filtered M3U
  mkdirSync('output', { recursive: true });
  const selected = allChannels.filter(ch => selectedSet.has(ch.tvgId));
  writeFileSync(PLAYLIST_PATH, buildM3u(selected, favSet), 'utf8');
  console.log(`[selector] Written ${PLAYLIST_PATH}`);
}

